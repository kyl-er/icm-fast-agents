"""Schema v2. Changes from v1, each one a response to something round 1 showed (04-rounds/round-1/NOTES.md):

1. Label definitions now state their precedence. Round 1's biggest error was mass mail that contains a call to
   action ("register now", "approve", "contact us") being labelled `action`.
2. `requests` is split: requests made personally to the recipient versus generic calls to action. v1 extracted
   "Register for the LDC Forum" as a request, and the decision model then had every reason to say `action`.
3. New field `written_for_recipient`, and `sender_kind` / `audience` descriptions say how to judge them.
4. The decision model also gets the from / to / subject headers. Extraction had dropped the cues that mark bulk mail.
5. `meeting` records whether the recipient has to respond, to separate invitations from mentions of a meeting.
"""
from typing import Literal, Optional
from pydantic import BaseModel, Field

VERSION = 'v2'
FACTS_STATE_KEEPS_HEADERS = True
LABELS = {
    'bulk': 'a newsletter, marketing email, automated or system-generated message, or an announcement sent to many people. '
            'Choose this even when it contains a call to action such as "register", "approve" or "contact us"',
    'personal': 'not about work: family, friends, jokes, private plans, chit-chat. Choose this even when it asks something',
    'meeting': 'written to the recipient and mainly about arranging a meeting, call or event: an invitation, a time change, '
               '"are you free", dial-in details. Choose this even when it asks for a confirmation',
    'action': 'a person asks the recipient specifically to do something or to answer a question, and it is none of the above',
    'info': 'work information with nothing asked of the recipient: a report, status, FYI, forwarded material, an answer, a thank-you',
}


class Request(BaseModel):
    what: str = Field(description='What is asked, in at most 12 words')
    deadline: Optional[str] = Field(None, description='Deadline as written in the email, or null')


class Meeting(BaseModel):
    what_and_when: str = Field(description='The meeting, call or event and its time, in at most 15 words')
    recipient_must_respond: bool = Field(description='True if the recipient is asked to attend, confirm or pick a time')


class EmailFacts(BaseModel):
    """Facts read from one email. Only what the text supports."""
    summary: str = Field(description='One sentence: what this email is')
    sender_kind: Literal['person', 'automated_system', 'mailing_list_or_marketing', 'unknown'] = Field(
        description='person: an individual wrote it by hand. automated_system: generated by software (receipts, logs, reminders, '
                    'schedulers). mailing_list_or_marketing: newsletters, promotions, vendor mailings, list posts')
    audience: Literal['one_person', 'small_group', 'many_people', 'unknown'] = Field(
        description='Count the To and Cc addresses. A distribution list or "all employees" is many_people. Up to about 6 named people is small_group')
    written_for_recipient: bool = Field(
        description='True only if a person wrote this specifically for the recipient or a small named group. '
                    'False for form letters, newsletters, notifications and announcements')
    personal_requests: list[Request] = Field(
        default_factory=list,
        description='Things a person asks the recipient specifically to do. Empty if none. Do NOT list generic calls to action here')
    generic_calls_to_action: list[str] = Field(
        default_factory=list,
        description='Calls to action aimed at any reader: "register now", "click here", "contact us with questions", "see attached"')
    questions: list[str] = Field(default_factory=list, description='Direct questions the recipient is expected to answer. Empty if none')
    meeting: Optional[Meeting] = Field(None, description='A meeting, call or event this email arranges. Null if it only mentions one in passing')
    work_related: bool = Field(description='True if the email is about work')


EXTRACT_PROMPT = """Read the email and fill in the fields. Use only what the email says. Keep text fields short.
The recipient is the person whose mailbox this is (the To: address).
Quoted earlier messages below "-----Original Message-----" or "Forwarded by" are context: describe the newest message."""

_URG = ['never: nothing to do', 'some time: no deadline', 'this week', 'today or tomorrow']
QUESTIONS_FACTS = {
    'triage': {'type': 'choice', 'instructions': 'Which kind of email is the one described by `facts` and `headers`? '
               'Check the options in the order given and choose the first that fits.', 'criteria': LABELS},
    'needs_reply': {'type': 'noul', 'instructions': 'Does the sender expect the recipient to write back?',
                    'criteria': {'true': 'a person asked a question, or asked to confirm, RSVP or respond', 'false': 'no response is expected, or the email is automated or mass mail'}},
    'urgency': {'type': 'score', 'instructions': 'How soon does the recipient need to deal with this email?', 'criteria': _URG},
}
QUESTIONS_RAW = {
    'triage': {**QUESTIONS_FACTS['triage'], 'instructions': 'Which kind of email is `email`, for its recipient? '
               'Check the options in the order given and choose the first that fits.'},
    'needs_reply': QUESTIONS_FACTS['needs_reply'],
    'urgency': QUESTIONS_FACTS['urgency'],
}


class Direct(BaseModel):
    """The no-decision-model baseline: the fast LLM answers the three questions itself."""
    triage: Literal['bulk', 'personal', 'meeting', 'action', 'info']
    needs_reply: bool
    urgency: Literal[0, 1, 2, 3] = Field(description='0 never, 1 some time, 2 this week, 3 today or tomorrow')


DIRECT_PROMPT = ('Triage this email for its recipient. Check the labels in the order given and choose the first that fits.\n'
                 + '\n'.join(f'- {k}: {v}' for k, v in LABELS.items()))
