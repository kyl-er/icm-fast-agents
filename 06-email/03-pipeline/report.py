#!/usr/bin/env python3
"""report.py: write 06-email/RESULTS.md from the metrics files of every round. Run after analyze.py."""
import json, pathlib

E = pathlib.Path(__file__).resolve().parent.parent
NAMES = {'extract+jev': 'Mercury 3 extracts, Jev decides (with the decision model)', 'llm': 'Mercury 3 alone (without it)', 'jev': 'Jev alone on the raw email'}
pct = lambda v: '-' if v is None else f'{v:.0%}'
ms = sorted(E.glob('04-rounds/round-*/metrics*.json'), key=lambda p: (json.loads(p.read_text())['tag'] != '', p.parent.name, p.name))
M = [json.loads(p.read_text()) for p in ms]
dev = [m for m in M if not m['tag']]
held = [m for m in M if m['tag']]
out = ['# Email demo: results', '',
       'Generated by `06-email/03-pipeline/report.py` from `04-rounds/round-*/metrics*.json`. Do not edit by hand.', '',
       '**Task.** Triage one email for its recipient into one of five labels (bulk, personal, meeting, action, info) and say whether a reply is expected.', '',
       '**How the sample was checked.** 120 emails (60 from the development split, 60 held out) were labelled by an AI model, '
       'Claude Opus 5.5, reading each email exactly as the pipelines see it (headers and the first 2,500 characters), with the written rules in '
       '`05-gold/README.md`, before and without seeing any pipeline output. **No human checked the labels.** The labeller marked 43 of the 120 as a '
       'close call between two labels; "lenient" accuracy also accepts its runner-up label. With 60 emails, one email is 1.7 points, so differences '
       'of a few points between routes are not meaningful.', '']
if held:
    out += ['## Held-out test (60 emails never used while tuning)', '',
            '| Schema | Route | Triage accuracy | Lenient | Reply accuracy | Failed calls | Median latency | Cost per email | Cost per 1,000 |',
            '|---|---|---|---|---|---|---|---|---|']
    for m in held:
        for k, x in m['modes'].items():
            out.append(f"| {m['schema']} | {NAMES[k]} | **{pct(x['triage_acc'])}** ({round(x['triage_acc'] * x['gold_n'])}/{x['gold_n']}) | {pct(x['triage_acc_lenient'])} | "
                       f"{pct(x['needs_reply_acc'])} | {x['errors']} | {x['median_ms']} ms | ${x['cost_per_email_usd']:.6f} | ${x['cost_per_email_usd'] * 1000:.2f} |")
    out.append('')
out += ['## The flywheel: three rounds on the same 200 development emails', '',
        'Accuracy is on the 60 gold-labelled emails inside the batch. Failed calls count as wrong; "answered" leaves them out.', '',
        '| Round | Schema | Route | Triage accuracy | Answered only | Lenient | Reply accuracy | Failed calls of 200 | Median latency | Cost per email |', '|---|---|---|---|---|---|---|---|---|---|']
for m in dev:
    for k, x in m['modes'].items():
        out.append(f"| {m['round']} | {m['schema']} | {NAMES[k]} | **{pct(x['triage_acc'])}** | {pct(x.get('triage_acc_answered'))} | {pct(x['triage_acc_lenient'])} | {pct(x['needs_reply_acc'])} | "
                   f"{x['errors']} | {x['median_ms']} ms | ${x['cost_per_email_usd']:.6f} |")
out += ['', '| Round | All three routes agree | ' + ' | '.join(dev[0]['agreement']) + ' |', '|---|---|' + '---|' * len(dev[0]['agreement'])]
for m in dev:
    out.append(f"| {m['round']} | {pct(m['all_agree'])} | " + ' | '.join(pct(v) for v in m['agreement'].values()) + ' |')
conf = [(m, k, x) for m in M for k, x in m['modes'].items() if x.get('acc_conf_high') is not None]
if conf:
    out += ['', '## Does the decision model\'s confidence mean anything?', '',
            'Gold emails split at the median confidence of each run: accuracy on the more confident half against the less confident half.', '',
            '| Round | Route | Median confidence | Accuracy, confident half | Accuracy, other half |', '|---|---|---|---|---|']
    for m, k, x in conf:
        out.append(f"| {m['round']}{' ' + m['tag'] if m['tag'] else ''} | {NAMES[k]} | {x['conf_median']} | {pct(x['acc_conf_high'])} | {pct(x['acc_conf_low'])} |")
notes = E / '04-rounds/SUMMARY.md'
if notes.exists():
    out += ['', notes.read_text().strip()]
(E / 'RESULTS.md').write_text('\n'.join(out) + '\n')
print('wrote 06-email/RESULTS.md')
