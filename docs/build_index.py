#!/usr/bin/env python3
"""Regenerate docs/INDEX.md: every documentation file in the repo with its first heading and first sentence."""
import pathlib, re, subprocess
ROOT = pathlib.Path(__file__).resolve().parent.parent
files = subprocess.run(['git', 'ls-files', '-co', '--exclude-standard', '*.md'], cwd=ROOT, capture_output=True, text=True).stdout.split('\n')
SKIP = ('vault/', 'node_modules/', 'scratch/', '04-rounds/round-', 'cli-index/cards/')
rows = []
for f in sorted(x for x in files if x and not x.startswith(SKIP) and not any(s in x for s in SKIP)):
    t = (ROOT / f).read_text(errors='replace')
    t = re.sub(r'^---\n.*?\n---\n', '', t, flags=re.S)
    h = re.search(r'^#\s+(.+)$', t, re.M)
    body = [l.strip() for l in t.splitlines() if l.strip() and not l.startswith(('#', '|', '```', '-', '>', '*'))]
    first = re.split(r'(?<=[.:])\s', body[0])[0][:150] if body else ''
    rows.append((f, h.group(1) if h else '', first))
out = ['# Documentation index', '', 'Generated by `python3 docs/build_index.py`. Start with `README.md`, then `DEMO.md`.', '',
       '| File | Title | What it says |', '|---|---|---|']
out += [f'| [`{f}`](../{f}) | {h} | {s} |' for f, h, s in rows]
out += ['', 'Also: one card per CLI command in `02-agent/cli-index/cards/`, and per-round notes in `06-email/04-rounds/round-N/NOTES.md`.']
(ROOT / 'docs/INDEX.md').write_text('\n'.join(out) + '\n')
print(len(rows), 'files indexed')
